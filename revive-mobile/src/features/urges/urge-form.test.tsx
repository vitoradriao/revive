import React from 'react';
import { AppState } from 'react-native';
import { act, fireEvent, render, screen, waitFor } from '@testing-library/react-native';
import { beforeEach, expect, it, jest } from '@jest/globals';
import { UrgeForm } from './urge-form';
import type { Addiction } from '@/domain/types';
import type { useReviveMutations } from '@/features/mutations/use-revive-mutations';
import { getPendingMutations, getUrgeReceipt } from '@/core/storage/database';

const mockSave = jest.fn<ReturnType<typeof useReviveMutations>['createUrgeEventWithReceipt']>();
const mockPush = jest.fn();
let mockGeneration = 1;
let mockNotifyCache: (() => void) | undefined;
jest.mock('expo-router', () => ({ useRouter: () => ({ push: mockPush }) }));
jest.mock('@/features/mutations/use-revive-mutations', () => ({ useReviveMutations: () => ({ createUrgeEventWithReceipt: mockSave }) }));
jest.mock('@/features/auth/session-context', () => ({ useSession: () => ({ user: { id: 'a' } }) }));
jest.mock('@/core/storage/database', () => ({ getPendingMutations: jest.fn(), getUrgeReceipt: jest.fn() }));
jest.mock('@/core/auth/token-store', () => ({ tokenStore: { getGeneration: () => mockGeneration, isCurrent: (generation: number) => mockGeneration === generation } }));
jest.mock('@/domain/urge-time', () => ({ ...jest.requireActual<typeof import('@/domain/urge-time')>('@/domain/urge-time'), deviceTimezone: () => 'America/Sao_Paulo' }));
jest.mock('@react-native-community/netinfo', () => ({ addEventListener: () => () => {} }));
jest.mock('@/core/query/client', () => ({ queryClient: { getQueryCache: () => ({ subscribe: (callback: (event: {query: {queryKey:string[]}}) => void) => { mockNotifyCache = () => callback({query:{queryKey:['bootstrap','a']}}); return () => {}; } }) } }));
jest.mock('react-native-safe-area-context', () => ({ useSafeAreaInsets: () => ({ top: 0, bottom: 0, left: 0, right: 0 }) }));
jest.mock('lucide-react-native', () => ({ CalendarDays: () => null, ChevronDown: () => null, ChevronLeft: () => null, ChevronRight: () => null, X: () => null, Eye: () => null, EyeOff: () => null }));
const habit: Addiction = { id:'habit',usuario_id:'a',nome_vicio:'Sintetico',data_inicio:'2026-01-01',ativo:true };
beforeEach(() => {
  jest.clearAllMocks(); mockGeneration = 1; mockNotifyCache = undefined;
  jest.spyOn(AppState,'addEventListener').mockReturnValue({remove:jest.fn()});
  mockSave.mockResolvedValue({id:'intent',status:'queued'});
  jest.mocked(getPendingMutations).mockResolvedValue([{id:'intent',status:'pending'}] as never);
  jest.mocked(getUrgeReceipt).mockResolvedValue(null);
});
it('saves intensity zero without a long diary, leaves descriptions optional and confirms no counter reset', async () => {
  await render(<UrgeForm habit={habit} />);
  await fireEvent.press(screen.getByLabelText('Intensidade 0 de 10'));
  await fireEvent.press(screen.getByText('Salvar vontade'));
  await waitFor(() => expect(mockSave).toHaveBeenCalledTimes(1));
  expect(mockSave).toHaveBeenCalledWith(expect.objectContaining({vicio_id:'habit',intensidade:0,gatilhos:[],nota:'',acao_realizada:'',resultado:'',timezone:'America/Sao_Paulo'}));
  expect(screen.getByText(/Vontade salva no aparelho; aguardando sincroniza/)).toBeTruthy();
  expect(screen.queryByText('Salvar vontade')).toBeNull();
  expect(screen.queryByText('Preciso de apoio agora')).toBeNull();
});
it('allows accessible numeric entry, editing triggers before save and a validated past moment', async () => {
  await render(<UrgeForm habit={habit} />);
  await fireEvent.changeText(screen.getByLabelText('Intensidade (0 a 10)'),'10');
  await fireEvent.press(screen.getByLabelText('Estresse'));
  await fireEvent.press(screen.getByLabelText('Rotina'));
  await fireEvent.press(screen.getByLabelText('Rotina'));
  await fireEvent.changeText(screen.getByLabelText('Data do episódio'),'12102026');
  await fireEvent.changeText(screen.getByLabelText('Horário (HH:mm)'),'22:45');
  await fireEvent.changeText(screen.getByLabelText('Nota (opcional)'),'Relato');
  await fireEvent.press(screen.getByText('Salvar vontade'));
  await waitFor(() => expect(mockSave).toHaveBeenCalledWith(expect.objectContaining({intensidade:10,gatilhos:['estresse'],occurred_at:'2026-10-13T01:45:00.000Z',nota:'Relato'})));
});
it('keeps all fields when local persistence fails and prevents an involuntary double send', async () => {
  let finish!: (receipt:{id:string;status:'queued'}) => void;
  mockSave.mockImplementation(() => new Promise(resolve => {finish=resolve;}));
  await render(<UrgeForm habit={habit} />);
  await fireEvent.press(screen.getByLabelText('Intensidade 4 de 10'));
  await fireEvent.changeText(screen.getByLabelText('Nota (opcional)'),'Preserved');
  await fireEvent.press(screen.getByText('Salvar vontade'));
  await waitFor(() => expect(mockSave).toHaveBeenCalledTimes(1));
  await fireEvent.press(screen.getByRole('button',{name:'Salvar vontade'}));
  expect(mockSave).toHaveBeenCalledTimes(1);
  await act(async () => {finish({id:'intent',status:'queued'});});
  await fireEvent.press(screen.getByText('Registrar outra vontade'));
  mockSave.mockRejectedValue(new Error('SQLite unavailable'));
  await fireEvent.press(screen.getByLabelText('Intensidade 3 de 10'));
  await fireEvent.changeText(screen.getByLabelText('Nota (opcional)'),'Preserved again');
  await fireEvent.press(screen.getByText('Salvar vontade'));
  await waitFor(() => expect(screen.getByText('SQLite unavailable')).toBeTruthy());
  expect(screen.getByLabelText('Nota (opcional)').props.value).toBe('Preserved again');
});
it('rejects missing/invalid intensity and future civil time without sending', async () => {
  await render(<UrgeForm habit={habit} />);
  await fireEvent.press(screen.getByText('Salvar vontade'));
  expect(mockSave).not.toHaveBeenCalled();
  await fireEvent.changeText(screen.getByLabelText('Intensidade (0 a 10)'),'11');
  await fireEvent.press(screen.getByText('Salvar vontade'));
  expect(mockSave).not.toHaveBeenCalled();
  await fireEvent.changeText(screen.getByLabelText('Intensidade (0 a 10)'),'4');
  await fireEvent.changeText(screen.getByLabelText('Data do episódio'),'13102099');
  await fireEvent.press(screen.getByText('Salvar vontade'));
  expect(mockSave).not.toHaveBeenCalled();
});
it('preserves draft while archival disables new events, then enables it on reactivation', async () => {
  const component=await render(<UrgeForm habit={habit} />);
  await fireEvent.changeText(screen.getByLabelText('Nota (opcional)'),'Local draft');
  await component.rerender(<UrgeForm habit={{...habit,ativo:false}} />);
  expect(screen.getByRole('button',{name:'Salvar vontade'})).toBeDisabled();
  expect(screen.getByLabelText('Nota (opcional)').props.value).toBe('Local draft');
  await component.rerender(<UrgeForm habit={habit} />);
  expect(screen.getByRole('button',{name:'Salvar vontade'})).toBeEnabled();
});
it('shows a failed durable intent and keeps the submitted fields for recovery', async () => {
  mockSave.mockResolvedValue({id:'intent',status:'failed'});
  await render(<UrgeForm habit={habit} />);
  await fireEvent.press(screen.getByLabelText('Intensidade 2 de 10'));
  await fireEvent.changeText(screen.getByLabelText('Resultado (opcional)'),'Relato final');
  await fireEvent.press(screen.getByText('Salvar vontade'));
  await waitFor(() => expect(screen.getByText(/com falha na sincronização/)).toBeTruthy());
  expect(screen.getByLabelText('Resultado (opcional)').props.value).toBe('Relato final');
  await fireEvent.press(screen.getByText('Resolver envio pendente'));
  expect(mockPush).toHaveBeenCalledWith('/(app)/sync');
});
it('updates the queued receipt after canonical reconciliation and suppresses old account publication', async () => {
  await render(<UrgeForm habit={habit} />);
  await fireEvent.press(screen.getByLabelText('Intensidade 1 de 10'));
  await fireEvent.press(screen.getByText('Salvar vontade'));
  await waitFor(() => expect(mockNotifyCache).toBeDefined());
  jest.mocked(getPendingMutations).mockResolvedValue([]);
  jest.mocked(getUrgeReceipt).mockResolvedValue({id:'server'} as never);
  await act(async () => {mockNotifyCache?.();});
  await waitFor(() => expect(screen.getByText(/Vontade sincronizada/)).toBeTruthy());
});
